import React, { useState, useEffect } from 'react';
import { X, Calendar, AlertCircle, Save } from 'lucide-react';

export default function ProjectModal({ isOpen, onClose, onSave, projectToEdit, isSubmitting }) {
  const isEditing = Boolean(projectToEdit && projectToEdit.id);

  const [formData, setFormData] = useState({
    name: '',
    description: '',
    startDate: '',
    deadline: '',
    status: 'NOT_STARTED',
  });

  const [errors, setErrors] = useState({});

  useEffect(() => {
    if (projectToEdit) {
      setFormData({
        name: projectToEdit.name || '',
        description: projectToEdit.description || '',
        startDate: projectToEdit.startDate || '',
        deadline: projectToEdit.deadline || '',
        status: projectToEdit.status || 'NOT_STARTED',
      });
    } else {
      // Default dates: today for start date, 30 days later for deadline
      const today = new Date().toISOString().split('T')[0];
      const thirtyDaysLater = new Date(Date.now() + 30 * 24 * 60 * 60 * 1000)
        .toISOString()
        .split('T')[0];

      setFormData({
        name: '',
        description: '',
        startDate: today,
        deadline: thirtyDaysLater,
        status: 'NOT_STARTED',
      });
    }
    setErrors({});
  }, [projectToEdit, isOpen]);

  if (!isOpen) return null;

  const validate = () => {
    const newErrors = {};

    if (!formData.name || !formData.name.trim()) {
      newErrors.name = 'Project name cannot be empty.';
    }

    if (!formData.description || !formData.description.trim()) {
      newErrors.description = 'Project description cannot be empty.';
    }

    if (!formData.startDate) {
      newErrors.startDate = 'Start date is required.';
    }

    if (!formData.deadline) {
      newErrors.deadline = 'Deadline is required.';
    }

    if (formData.startDate && formData.deadline) {
      if (formData.deadline < formData.startDate) {
        newErrors.deadline = 'Deadline cannot be earlier than start date.';
      }
    }

    if (!['NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'].includes(formData.status)) {
      newErrors.status = 'Status must be Not Started, In Progress, or Completed.';
    }

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData((prev) => ({
      ...prev,
      [name]: value,
    }));

    // Clear field-specific error as user types
    if (errors[name]) {
      setErrors((prev) => {
        const updated = { ...prev };
        delete updated[name];
        return updated;
      });
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    if (!validate()) {
      return;
    }

    onSave({
      ...formData,
      name: formData.name.trim(),
      description: formData.description.trim(),
    });
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div
        className="modal-container"
        onClick={(e) => e.stopPropagation()}
        role="dialog"
        aria-modal="true"
        aria-labelledby="modal-title"
      >
        <div className="modal-header">
          <div>
            <h2 id="modal-title" className="modal-title">
              {isEditing ? 'Edit Project' : 'Add New Project'}
            </h2>
            <p className="modal-subtitle">
              {isEditing
                ? `Update details for Project #${projectToEdit.id}`
                : 'Enter software project details and timeline'}
            </p>
          </div>
          <button
            type="button"
            className="modal-close-btn"
            onClick={onClose}
            aria-label="Close modal"
          >
            <X size={20} />
          </button>
        </div>

        <form onSubmit={handleSubmit} noValidate className="modal-form">
          {/* Project ID (read-only preview) */}
          <div className="form-group">
            <label className="form-label" htmlFor="projectId">
              Project ID
            </label>
            <input
              id="projectId"
              type="text"
              className="form-input form-input-readonly"
              value={isEditing ? `#${projectToEdit.id}` : 'Auto-generated by Database'}
              disabled
              readOnly
            />
          </div>

          {/* Project Name */}
          <div className="form-group">
            <label className="form-label required" htmlFor="name">
              Project Name
            </label>
            <input
              id="name"
              name="name"
              type="text"
              className={`form-input ${errors.name ? 'input-error' : ''}`}
              placeholder="e.g. Campus Navigation System"
              value={formData.name}
              onChange={handleChange}
              autoFocus
            />
            {errors.name && (
              <div className="error-message">
                <AlertCircle size={14} />
                <span>{errors.name}</span>
              </div>
            )}
          </div>

          {/* Description */}
          <div className="form-group">
            <label className="form-label required" htmlFor="description">
              Description
            </label>
            <textarea
              id="description"
              name="description"
              rows={3}
              className={`form-textarea ${errors.description ? 'input-error' : ''}`}
              placeholder="Describe the project objectives, technologies, and deliverables..."
              value={formData.description}
              onChange={handleChange}
            />
            {errors.description && (
              <div className="error-message">
                <AlertCircle size={14} />
                <span>{errors.description}</span>
              </div>
            )}
          </div>

          {/* Date Row: Start Date & Deadline */}
          <div className="form-row">
            <div className="form-group">
              <label className="form-label required" htmlFor="startDate">
                Start Date
              </label>
              <div className="input-with-icon">
                <Calendar size={16} className="field-icon" />
                <input
                  id="startDate"
                  name="startDate"
                  type="date"
                  className={`form-input ${errors.startDate ? 'input-error' : ''}`}
                  value={formData.startDate}
                  onChange={handleChange}
                />
              </div>
              {errors.startDate && (
                <div className="error-message">
                  <AlertCircle size={14} />
                  <span>{errors.startDate}</span>
                </div>
              )}
            </div>

            <div className="form-group">
              <label className="form-label required" htmlFor="deadline">
                Deadline
              </label>
              <div className="input-with-icon">
                <Calendar size={16} className="field-icon" />
                <input
                  id="deadline"
                  name="deadline"
                  type="date"
                  className={`form-input ${errors.deadline ? 'input-error' : ''}`}
                  value={formData.deadline}
                  onChange={handleChange}
                />
              </div>
              {errors.deadline && (
                <div className="error-message">
                  <AlertCircle size={14} />
                  <span>{errors.deadline}</span>
                </div>
              )}
            </div>
          </div>

          {/* Status */}
          <div className="form-group">
            <label className="form-label required" htmlFor="status">
              Status
            </label>
            <select
              id="status"
              name="status"
              className={`form-select ${errors.status ? 'input-error' : ''}`}
              value={formData.status}
              onChange={handleChange}
            >
              <option value="NOT_STARTED">Not Started</option>
              <option value="IN_PROGRESS">In Progress</option>
              <option value="COMPLETED">Completed</option>
            </select>
            {errors.status && (
              <div className="error-message">
                <AlertCircle size={14} />
                <span>{errors.status}</span>
              </div>
            )}
          </div>

          {/* Modal Actions */}
          <div className="modal-footer">
            <button
              type="button"
              className="btn btn-secondary"
              onClick={onClose}
              disabled={isSubmitting}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn-primary"
              disabled={isSubmitting}
            >
              <Save size={16} />
              <span>{isSubmitting ? 'Saving...' : isEditing ? 'Update Project' : 'Create Project'}</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
